package engine

import "context"

// AuthzRequest — запрос на проверку права.
type AuthzRequest struct {
	Action  Action
	Subject Subject

	// Target — объект действия, если он уже загружен обработчиком:
	// конкретный комментарий, вложение, значение поля.
	//
	// Часть правил нельзя проверить до загрузки объекта — какой именно
	// комментарий правят, видно только после запроса по идентификатору
	// из пути. Поэтому проверка выполняется дважды: сначала по тому, что
	// известно из маршрута, затем — с объектом. Это один и тот же
	// механизм, вызванный в двух точках, а не два независимых слоя прав.
	//
	// Движок обязан быть готов к nil: проверка «до объекта» приходит
	// с пустым Target.
	Target any
}

// TargetAs приводит объект действия к нужному типу.
// Второе значение false — объекта нет или он другого типа.
func TargetAs[T any](req AuthzRequest) (T, bool) {
	v, ok := req.Target.(T)
	return v, ok
}

// Authorizer — движок, управляющий правами доступа.
// Опциональный: не реализован — права считает ядро.
type Authorizer interface {
	Authorize(ctx context.Context, req AuthzRequest) (Verdict, error)
}
