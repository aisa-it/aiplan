package engine

import (
	"context"

	"gorm.io/gorm"
)

// PropertyPolicy — видимость шаблонов кастомных полей задачи для субъекта.
// Опционален: без него ядро применяет своё правило по роли в проекте.
type PropertyPolicy interface {
	// ScopePropertyTemplates навешивает на запрос по project_property_templates
	// ограничения видимости для субъекта. Единственный источник правды:
	// карточка задачи, списки, настройки проекта и доступные значения
	// опираются на него, поэтому не могут разойтись.
	//
	// Запрос может охватывать шаблоны нескольких проектов (списки задач),
	// поэтому реализация не должна рассчитывать на проект субъекта —
	// ограничение выражается через project_id самой строки шаблона.
	ScopePropertyTemplates(ctx context.Context, s Subject, q *gorm.DB) *gorm.DB
}
