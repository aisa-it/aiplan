package engine

import (
	"github.com/aisa-it/aiplan/aiplan.go/pkg/dao"
	"gorm.io/gorm"
)

// Subject — участники и сущности проверяемого запроса.
//
// Намеренно не содержит ничего от HTTP: движок принимает решение по
// предметным данным (кто, над чем), а не по методу запроса и пути роута.
// Это позволяет применять один и тот же движок и к HTTP-ручкам, и к MCP.
//
// Геттеры ленивые: сущность загружается при первом обращении, поэтому
// движок, которому достаточно роли, не оплачивает загрузку задачи.
// Реализуется *apicontext.APIContext.
type Subject interface {
	// DB — соединение, привязанное к текущему запросу.
	DB() *gorm.DB
	// User — пользователь, выполняющий действие. Для запросов без
	// авторизации возвращает nil.
	User() *dao.User

	Workspace() *dao.Workspace
	WorkspaceMember() *dao.WorkspaceMember
	Project() *dao.Project
	ProjectMember() *dao.ProjectMember
	Sprint() *dao.Sprint
	Doc() *dao.Doc

	// Issue — задача запроса. В issue-скоупе ядро гарантирует, что
	// исполнители уже подгружены.
	Issue() *dao.Issue

	// Err — первая ошибка ленивой загрузки. Ядро обязано проверить её
	// после вызова движка: ошибка загрузки не должна молча означать отказ
	// или, тем более, разрешение.
	Err() error
}
